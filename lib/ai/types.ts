import type { z } from "zod";

/**
 * The model boundary, stated once and owned by nobody in particular.
 *
 * ## Why this layer exists at all
 *
 * The product requirement is that Roamly runs for free, with no account and no
 * key. That rules out designing around one vendor: the app has to work when a
 * Gemini key is present, when a local Ollama is running, and when neither is —
 * and the three cases must be indistinguishable to everything downstream.
 *
 * So the pipeline never talks to a provider. It talks to a `StructuredGenerator`,
 * hands it a Zod schema, and gets back one of three things: a validated value, a
 * refusal, or an explanation of why no answer is available. **No provider
 * response object crosses this boundary** — not a Gemini `candidate`, not an
 * Ollama message, not an HTTP status. Those live and die inside their adapter.
 *
 * The deterministic demo planner implements the same interface. That is not a
 * trick to make the types line up: it is what guarantees the free path exercises
 * the same validation, the same canonical attachment and the same failure
 * handling as a real model, rather than being a separate code path nobody tests.
 */

/** The concrete producers. `deterministic` is not a model and does not pretend to be. */
export type AiProviderId = "gemini" | "ollama" | "deterministic";

/**
 * What the caller asked for, which is not the same as what they get.
 *
 * `auto` is the default and resolves by configuration. The three explicit values
 * are demands: selecting `gemini` without a key reports `not_configured` rather
 * than quietly falling back, because a silent downgrade from a real model to the
 * demo planner is exactly the substitution this phase must not make.
 */
export type AiProviderPreference = "auto" | AiProviderId;

/**
 * Which prompt is being run. Adapters may pace or size by this.
 *
 * `refinement` (Phase 6A) is a much smaller request than the other three: one stop,
 * one backup or one day, against a short candidate list. It shares the interface so
 * there is exactly one AI-client architecture in the codebase.
 */
export type AiOperation = "strategy" | "assembly" | "repair" | "refinement";

/**
 * Token counts, where the provider reports them.
 *
 * Every field optional: Ollama reports differently from Gemini, and inventing a
 * zero for a count a provider did not send would be a fabricated fact about our
 * own usage. Diagnostics only — never rendered as a cost.
 */
export type NormalizedModelUsage = {
  inputTokens?: number;
  outputTokens?: number;
};

export type StructuredGenerationRequest<TSchema extends z.ZodType> = {
  operation: AiOperation;
  /**
   * The frozen instruction. Stable across calls for one operation so a provider
   * that supports prompt caching can benefit without us reshaping the prompt.
   */
  systemInstruction: string;
  /** Serialised into the user turn by real adapters; re-parsed by the deterministic one. */
  input: unknown;
  /**
   * The contract, used two ways: embedded in the prompt as JSON Schema, and handed
   * to a provider that supports constrained decoding.
   *
   * Adapters may not relax it and may not *enforce* it either — see
   * `StructuredGenerator.generate` for why validation is deliberately downstream.
   */
  outputSchema: TSchema;
  /** Human-readable name used in the JSON contract embedded in the prompt. */
  schemaName: string;
  signal?: AbortSignal;
};

/**
 * Why no answer is available.
 *
 * Deliberately the same vocabulary the routing and OSM layers already use, so a
 * failure reads the same wherever it comes from. `empty_response` is separate
 * from `invalid_response` because they need different handling: a 200 with no
 * content is a provider quirk worth one honest retry decision, while unparseable
 * content is a contract problem.
 */
export type AiUnavailableReason =
  | "not_configured"
  | "rate_limited"
  | "timeout"
  | "provider_unavailable"
  | "invalid_response"
  | "empty_response"
  | "aborted"
  | "unknown";

export type StructuredGenerationResult<T> =
  | {
      status: "success";
      value: T;
      provider: AiProviderId;
      model: string;
      usage?: NormalizedModelUsage;
    }
  | {
      status: "refused";
      /** Plain language, safe to render. Never a provider name or a status code. */
      userMessage: string;
    }
  | {
      status: "unavailable";
      reason: AiUnavailableReason;
      userMessage: string;
    };

/**
 * One provider, normalised.
 *
 * `id` and `model` are labels for provenance and are safe to show. `model` for
 * the deterministic planner is a version string, not a model name, so nothing
 * downstream can print "generated by demo-planner-1" and have it read as a model.
 *
 * ## Why `value` is `unknown` rather than the schema's type
 *
 * An adapter that returned `z.infer<TSchema>` would have to run `parse()` itself,
 * and that is the wrong place for the decision — for one specific reason.
 *
 * Zod **strips** unknown keys. A model that volunteers `latitude` beside a
 * `placeId` parses cleanly and the fabrication silently disappears, so a validator
 * that only ever sees post-parse data can never report it. `lib/ai/prohibited.ts`
 * has to scan the **raw** payload, before anything is stripped, and it is a hard
 * failure when it finds something.
 *
 * So the adapter's job stops at transport and normalisation: get JSON out of a
 * provider, or say why not. `validateStrategy` and `validateAssembly` own the
 * verdict, and they own it on the raw object. The extra benefit is that a
 * schema-invalid answer becomes a structured violation report and one repair pass
 * rather than a dead end.
 */
export type StructuredGenerator = {
  readonly id: AiProviderId;
  readonly model: string;
  generate<TSchema extends z.ZodType>(
    request: StructuredGenerationRequest<TSchema>,
  ): Promise<StructuredGenerationResult<unknown>>;
};

/** True when a result carries a value. Narrowing helper, so callers stop guessing. */
export function isGenerationSuccess<T>(
  result: StructuredGenerationResult<T>,
): result is Extract<StructuredGenerationResult<T>, { status: "success" }> {
  return result.status === "success";
}
