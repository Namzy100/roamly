/**
 * Six disjoint windows, assigned in order.
 *
 * A fixed ladder rather than computed times: it guarantees no overlap and a
 * positive duration for every item without any arithmetic that could get it wrong,
 * and it leaves real gaps between stops so the schedule does not describe
 * teleportation. `MAX_SLOTS_PER_DAY` is six, so there is always a window.
 */
const WINDOWS: { start: string; end: string }[] = [
  { start: "09:00", end: "10:15" },
  { start: "10:45", end: "12:30" },
  { start: "13:00", end: "14:30" },
  { start: "15:00", end: "16:45" },
  { start: "17:15", end: "18:30" },
  { start: "19:30", end: "21:00" },
];

function buildAssembly(input: AssemblyInput): GeneratedTripAssembly {
  /**
   * Candidates are consumed globally, not per day.
   *
   * A trip that visits the same café every morning is not a trip. Tracking usage
   * across the whole itinerary is what makes day three differ from day one, and it
   * is why running out of candidates produces an honest `unavailable` rather than
   * a repeat.
   */
  const used = new Set<string>();
  const byCategory = groupByCategory(input.candidates);

  const days = input.strategy.days.map((strategyDay) => {
    const dateInfo = input.dayDates.find(
      (entry) => entry.dayNumber === strategyDay.dayNumber,
    );

    const items: GeneratedTripAssembly["days"][number]["items"] = [];
    const backups: GeneratedTripAssembly["days"][number]["backups"] = [];

    strategyDay.searchRequirements.forEach((slot, index) => {
      const window = WINDOWS[index % WINDOWS.length];
      const itemId = `d${strategyDay.dayNumber}-${slot.slotId.replace(/^d\d+-/, "")}`;

      const chosen = takeNext(byCategory, slot.category, used);
      if (!chosen) {
        items.push({
          kind: "unavailable",
          itemId,
          slotId: slot.slotId,
          reason: `No ${slot.category.replace(/_/g, " ")} was found in the OpenStreetMap search around this destination, so this slot is left open rather than filled with something invented.`,
          startTime: window.start,
          endTime: window.end,
        });
        return;
      }

      const cost = clampPartyCost({
        proposed: null,
        currency: input.currency,
        costClass: costClassFor(slot.category, slot.mealType),
        travelers: input.travelers,
      });

      items.push({
        kind: "place",
        itemId,
        slotId: slot.slotId,
        placeId: chosen.placeId,
        category: slot.category,
        mealType: slot.mealType,
        startTime: window.start,
        endTime: window.end,
        title: slotTitle(slot),
        description: describeCandidate(chosen, slot),
        estimatedCost: buildCostEstimate({
          amount: cost.amount,
          currency: input.currency,
          // Low throughout. A template has no basis for more confidence than that.
          confidence: "low",
        }),
        reservationRecommended: slot.mealType === "dinner",
      });

      /**
       * `peekNext`, not `takeNext`: a backup must not consume a candidate.
       *
       * Marking it used would let day one's backups exhaust the pool that day
       * three's actual stops need, turning a well-supplied destination into a
       * string of unavailable slots. A place appearing as day three's stop and
       * day one's backup is fine — the sample itinerary does exactly that.
       */
      const alternative = peekNext(byCategory, slot.category, used);
      if (alternative) {
        backups.push({
          backupId: `bk-${itemId}`,
          slotId: slot.slotId,
          placeId: alternative.placeId,
          reason: `Another ${categoryWords(slot.category)} from the same search, in case the first choice is closed or full.`,
        });
      } else {
        backups.push({
          backupId: `bk-${itemId}`,
          slotId: slot.slotId,
          reason: `No second ${categoryWords(slot.category)} was found nearby.`,
          unavailableReason:
            "The OpenStreetMap search returned no alternative of this kind, so there is no backup to offer.",
        });
      }
    });

    // A deliberate open block, in the first unused window. Honest about the shape
    // of a real day, and it guarantees a day is never a list of gaps alone.
    const freeWindow = WINDOWS[strategyDay.searchRequirements.length % WINDOWS.length];
    if (strategyDay.searchRequirements.length < WINDOWS.length) {
      items.push({
        kind: "non-place",
        itemId: `d${strategyDay.dayNumber}-open`,
        category: "free-time",
        startTime: freeWindow.start,
        endTime: freeWindow.end,
        title: "Unscheduled time",
        description:
          "Left deliberately open. The demo planner does not fill every hour, and the walk between two stops in an unfamiliar city usually takes longer than a schedule suggests.",
        estimatedCost: buildCostEstimate({
          amount: 0,
          currency: input.currency,
          confidence: "high",
        }),
      });
    }

    return {
      dayNumber: strategyDay.dayNumber,
      title: `Day ${strategyDay.dayNumber} — ${strategyDay.theme}`,
      summary: `${strategyDay.theme}${dateInfo ? ` (${dateInfo.weekday})` : ""}. ${countScheduled(items)} of ${strategyDay.searchRequirements.length} planned stops were matched to a real place from the OpenStreetMap search; anything unmatched is shown as an open slot rather than filled in.`,
      items,
      backups: backups.slice(0, 4),
    };
  });

  return {
    title: `${input.dayDates.length} days in ${input.destinationName}`,
    destinationOverview: `A ${input.dayDates.length}-day, ${input.pace}-pace outline for ${input.destinationName}, assembled by the demo planner. Every stop is a real place from OpenStreetMap, selected by category and nothing else — the demo planner has no local knowledge, no reviews and no prices, so treat this as a starting structure rather than a recommendation. Costs are category estimates and travel times are not calculated until you ask for real routes.`,
    recommendedNeighborhood: {
      name: input.strategy.recommendedBaseArea,
      why: "The demo planner centres its search on the geocoded centre of the destination, so the stops above cluster around it. It cannot tell you which district is nicest to stay in — that judgement needs local knowledge it does not have.",
    },
    days,
    practicalNotes: [
      {
        title: "These places are real; the commentary is generic",
        body: "Every stop comes from an OpenStreetMap search around this destination and carries its real identity and coordinates. The descriptions are template text, because the demo planner has no knowledge of these places beyond the map data.",
      },
      {
        title: "Costs are estimates, not prices",
        body: "Each figure is a typical cost for that kind of place, for your whole party, in your chosen currency. Nothing has been quoted, converted or booked.",
      },
      {
        title: "Opening hours are unverified",
        body: "Where OpenStreetMap records opening hours they are shown exactly as recorded and have not been interpreted. Confirm anything you are making a journey for.",
      },
      {
        title: "Travel times come later",
        body: "Use “Calculate real routes” on the trip page to get walking and driving times from OpenStreetMap road data. Until then no travel time is claimed.",
      },
    ],
  };
}

function groupByCategory(
  candidates: ModelPlaceCandidate[],
): Map<PlaceCategory, ModelPlaceCandidate[]> {
  const grouped = new Map<PlaceCategory, ModelPlaceCandidate[]>();
  for (const candidate of candidates) {
    const bucket = grouped.get(candidate.category);
    if (bucket) bucket.push(candidate);
    else grouped.set(candidate.category, [candidate]);
  }
  return grouped;
}

/**
 * The next unused candidate of a category, or null.
 *
 * Pure lookup with no fallback: there is deliberately no "closest other category"
 * rule. A missing café produces an open slot, not a bar relabelled as one.
 */
function takeNext(
  byCategory: Map<PlaceCategory, ModelPlaceCandidate[]>,
  category: PlaceCategory,
  used: Set<string>,
): ModelPlaceCandidate | null {
  const candidate = peekNext(byCategory, category, used);
  if (candidate) used.add(candidate.placeId);
  return candidate;
}

/** The same lookup without claiming the candidate. See the call site for why. */
function peekNext(
  byCategory: Map<PlaceCategory, ModelPlaceCandidate[]>,
  category: PlaceCategory,
  used: Set<string>,
): ModelPlaceCandidate | null {
  for (const candidate of byCategory.get(category) ?? []) {
    if (used.has(candidate.placeId)) continue;
    return candidate;
  }
  return null;
}

function slotTitle(slot: {
  mealType: MealType | null;
  category: PlaceCategory;
}): string {
  if (slot.mealType) {
    return `${slot.mealType[0].toUpperCase()}${slot.mealType.slice(1)}`;
  }
  const words = categoryWords(slot.category);
  return `${words[0].toUpperCase()}${words.slice(1)} stop`;
}

function categoryWords(category: PlaceCategory): string {
  return category.replace(/_/g, " ");
}

/**
 * A description built only from facts the candidate actually carries.
 *
 * Note what is absent: no adjective about quality, no claim about atmosphere, no
 * statement about when it is open. `sourceFacts` and `address` are copied from
 * OpenStreetMap, and the rest of the sentence is about the *itinerary* — which
 * slot this fills and why — which the planner does legitimately know.
 */
function describeCandidate(
  candidate: ModelPlaceCandidate,
  slot: { purpose: string; mealType: MealType | null },
): string {
  const parts = [
    slot.purpose,
    candidate.address
      ? `OpenStreetMap records the address as ${candidate.address}.`
      : "OpenStreetMap has no address recorded for this one.",
  ];

  if (candidate.cuisine) {
    parts.push(`Tagged as ${candidate.cuisine}.`);
  }
  if (candidate.openingHours) {
    parts.push(
      `Opening hours are recorded as “${candidate.openingHours}”, exactly as they appear in OpenStreetMap and not interpreted — check before you go.`,
    );
  }
  parts.push(
    "Chosen by category from the map search, so it is a real place rather than a recommendation.",
  );

  return parts.join(" ");
}

function countScheduled(
  items: GeneratedTripAssembly["days"][number]["items"],
): number {
  return items.filter((item) => item.kind === "place").length;
}

function round2(value: number): number {
  return Math.round(value * 100) / 100;
}
