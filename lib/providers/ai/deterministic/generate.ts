/**
 * The planner re-parses its input rather than trusting a type assertion.
 *
 * It receives the same `unknown` a real provider receives — that is what keeps the
 * interface honest — so it validates at its own boundary like every other module
 * in this codebase.
 */
const StrategyInputSchema = z.object({
  destinationName: z.string().min(1),
  dayCount: z.number().int().min(1).max(7),
  nightCount: z.number().int().min(0).max(6),
  pace: PaceSchema,
  vibes: z.array(z.string()),
  interests: z.array(z.string()),
  accommodation: z.string(),
  travelers: z.number().int().min(1),
  currency: z.string(),
});
type StrategyInput = z.infer<typeof StrategyInputSchema>;

const CandidateSchema = z.object({
  placeId: z.string().min(1),
  name: z.string().min(1),
  category: PlaceCategorySchema,
  categoryLabel: z.string().optional(),
  latitude: z.number(),
  longitude: z.number(),
  address: z.string().optional(),
  cuisine: z.string().optional(),
  openingHours: z.string().optional(),
  website: z.string().optional(),
  sourceFacts: z.array(z.string()),
});

const AssemblyInputSchema = z.object({
  destinationName: z.string().min(1),
  currency: z.enum(["EUR", "USD", "GBP", "AED"]),
  travelers: z.number().int().min(1),
  pace: PaceSchema,
  dayDates: z.array(
    z.object({
      dayNumber: z.number().int().min(1).max(7),
      date: z.string(),
      weekday: z.string(),
    }),
  ),
  strategy: z.object({
    recommendedBaseArea: z.string(),
    days: z.array(
      z.object({
        dayNumber: z.number().int().min(1).max(7),
        theme: z.string(),
        pace: PaceSchema,
        searchRequirements: z.array(
          z.object({
            slotId: z.string(),
            category: PlaceCategorySchema,
            purpose: z.string(),
            mealType: MealTypeSchema.nullable(),
            required: z.boolean(),
            targetTime: z.string().optional(),
          }),
        ),
      }),
    ),
  }),
  candidates: z.array(CandidateSchema),
});
type AssemblyInput = z.infer<typeof AssemblyInputSchema>;

