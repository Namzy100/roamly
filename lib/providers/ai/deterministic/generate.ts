/**
 * Interest and vibe → search categories.
 *
 * The one place this planner encodes any judgement, and it is judgement about
 * *categories*, which is safe: "someone who ticked museums wants museums and
 * galleries" is a statement about the request, not about the destination.
 */
const INTEREST_CATEGORIES: Partial<Record<Interest, PlaceCategory[]>> = {
  museums: ["museum", "gallery"],
  architecture: ["monument", "historic_site", "place_of_worship"],
  history: ["historic_site", "monument", "museum"],
  "local-markets": ["market"],
  coffee: ["cafe"],
  wine: ["winery", "bar"],
  "street-food": ["market", "fast_food"],
  "fine-dining": ["restaurant"],
  "live-music": ["music_venue", "theatre"],
  viewpoints: ["viewpoint"],
  beaches: ["beach"],
  "day-trips": ["attraction", "historic_site"],
  photography: ["viewpoint", "monument"],
  bookshops: ["shopping"],
};

const VIBE_CATEGORIES: Partial<Record<Vibe, PlaceCategory[]>> = {
  culture: ["museum", "theatre", "gallery"],
  food: ["market", "cafe"],
  nature: ["park", "garden", "viewpoint"],
  nightlife: ["bar", "music_venue"],
  relaxation: ["park", "garden", "beach"],
  adventure: ["viewpoint", "attraction"],
  shopping: ["shopping", "market"],
  romance: ["viewpoint", "garden"],
};

const ACCOMMODATION_CATEGORY: Record<string, PlaceCategory> = {
  boutique: "hotel",
  hotel: "hotel",
  luxury: "hotel",
  apartment: "guest_house",
  hostel: "hostel",
};

/** Fallback anchors, so a request with narrow interests still has a day shape. */
const FALLBACK_ANCHORS: PlaceCategory[] = [
  "attraction",
  "viewpoint",
  "museum",
  "park",
];

/** Stops per day, from the requested pace. Matches the labels in `PACE_OPTIONS`. */
const ANCHORS_PER_DAY: Record<Pace, number> = {
  relaxed: 1,
  balanced: 1,
  packed: 2,
};

const MEAL_SLOTS: Record<Pace, { mealType: MealType; category: PlaceCategory }[]> =
  {
    relaxed: [
      { mealType: "breakfast", category: "cafe" },
      { mealType: "lunch", category: "restaurant" },
    ],
    balanced: [
      { mealType: "breakfast", category: "cafe" },
      { mealType: "lunch", category: "restaurant" },
      { mealType: "dinner", category: "restaurant" },
    ],
    packed: [
      { mealType: "breakfast", category: "cafe" },
      { mealType: "lunch", category: "restaurant" },
      { mealType: "dinner", category: "restaurant" },
    ],
  };

function buildStrategy(input: StrategyInput): TripStrategy {
  const anchors = anchorPool(input);
  const meals = MEAL_SLOTS[input.pace];
  const anchorsPerDay = ANCHORS_PER_DAY[input.pace];

  const days = Array.from({ length: input.dayCount }, (_, index) => {
    const dayNumber = index + 1;
    const requirements: SearchRequirement[] = [];

    /**
     * Slot order is breakfast, anchors, lunch, dinner — which is *not* chronological
     * and does not need to be. Assembly schedules by time, and keeping the order
     * fixed keeps the positional slot ids stable for a given pace, which is what
     * makes the whole thing reproducible.
     */
    const template: {
      category: PlaceCategory;
      mealType: MealType | null;
      required: boolean;
      purpose: string;
    }[] = [];

    const breakfast = meals.find((meal) => meal.mealType === "breakfast");
    if (breakfast) {
      template.push({
        category: breakfast.category,
        mealType: "breakfast",
        required: true,
        purpose: "Somewhere to start the day within reach of the base area.",
      });
    }

    for (let slot = 0; slot < anchorsPerDay; slot += 1) {
      const category = anchors[(index * anchorsPerDay + slot) % anchors.length];
      template.push({
        category,
        mealType: null,
        required: slot === 0,
        purpose: `The day's ${slot === 0 ? "main" : "second"} stop, matched to the stated interests.`,
      });
    }

    for (const meal of meals) {
      if (meal.mealType === "breakfast") continue;
      template.push({
        category: meal.category,
        mealType: meal.mealType,
        required: true,
        purpose: `A ${meal.mealType} stop, kept near the day's other stops.`,
      });
    }

    // Day one looks for somewhere to stay, so the accommodation recommendation has
    // a real, discovered place behind it rather than an invented hotel. Optional:
    // a destination with no mapped accommodation must not fail the whole trip.
    if (dayNumber === 1) {
      template.push({
        category:
          ACCOMMODATION_CATEGORY[input.accommodation] ?? ("hotel" as PlaceCategory),
        mealType: null,
        required: false,
        purpose:
          "A place to stay in the base area, used for the accommodation estimate.",
      });
    }

    template.forEach((entry, slotIndex) => {
      requirements.push({
        slotId: `d${dayNumber}-s${slotIndex + 1}`,
        category: entry.category,
        purpose: entry.purpose,
        mealType: entry.mealType,
        required: entry.required,
        candidateLimit: 8,
      });
    });

    return {
      dayNumber,
      theme: dayTheme(dayNumber, input.dayCount),
      pace: input.pace,
      searchRequirements: requirements,
    };
  });

  return {
    /**
     * Every sentence below is either mechanically true of the request or is
     * explicitly labelled as template text. Nothing asserts local knowledge.
     */
    destinationSummary: `This itinerary was assembled by Roamly's demo planner, which is a deterministic template rather than a language model. The stops are real places taken from OpenStreetMap around ${input.destinationName}, chosen by category to match the ${input.dayCount}-day, ${input.pace}-pace request. The commentary is generic: the demo planner has no knowledge of ${input.destinationName} beyond the map data, and does not pretend to.`,
    recommendedBaseArea: `Central ${input.destinationName}`,
    languageNote:
      "The demo planner does not know which languages are spoken here. Check before you travel; a translation app and a few greetings go a long way anywhere.",
    currencyNote: `Costs below are planning estimates in ${input.currency}, from typical prices for each kind of place. They are not live prices and no currency has been converted.`,
    seasonalNote:
      "The demo planner does not know the weather or the season here. Check a forecast close to your dates, and treat outdoor stops as weather-dependent.",
    recommendedRadiusMeters: input.interests.includes("day-trips") ? 8_000 : 4_000,
    budgetAllocation: budgetAllocation(input),
    days,
    practicalConsiderations: [
      "Opening hours are not checked. Where OpenStreetMap has them they are shown raw and uninterpreted; confirm anything you are travelling across town for.",
      "Every cost is a category estimate for the whole party, not a price. Nothing here has been quoted or booked.",
      "Travel times between stops are not calculated until you ask for real routes on the trip page.",
      "The demo planner picks places by category and proximity only. It has no view on whether a place is any good.",
    ],
  };
}

/**
 * Ordered, deduplicated categories to build days around.
 *
 * Interests first because they are the more specific signal, then vibes, then the
 * fallbacks. Order is fully determined by the request's own array order, so the
 * same request always produces the same days.
 */
function anchorPool(input: StrategyInput): PlaceCategory[] {
  const pool: PlaceCategory[] = [];
  const add = (categories: PlaceCategory[] | undefined) => {
    for (const category of categories ?? []) {
      if (!pool.includes(category)) pool.push(category);
    }
  };

  for (const interest of input.interests) {
    add(INTEREST_CATEGORIES[interest as Interest]);
  }
  for (const vibe of input.vibes) {
    add(VIBE_CATEGORIES[vibe as Vibe]);
  }
  add(FALLBACK_ANCHORS);

  return pool;
}

/**
 * Day themes that describe the *plan*, not the destination.
 *
 * "Arrival day, kept short" is true of the itinerary. "Alfama, slowly" would be a
 * claim about a place the planner has never heard of.
 */
function dayTheme(dayNumber: number, dayCount: number): string {
  if (dayCount === 1) return "One day, the essentials";
  if (dayNumber === 1) return "Arrival day, kept short";
  if (dayNumber === dayCount) return "Last day, close to the base";
  return `Day ${dayNumber}, matched to your interests`;
}

/**
 * Shares that always sum to exactly 1.
 *
 * `buffer` absorbs the rounding rather than being computed independently, so the
 * reconciliation check in `validate-strategy.ts` passes exactly rather than within
 * tolerance — this planner should never be the thing that trips a tolerance.
 */
function budgetAllocation(input: StrategyInput): TripStrategy["budgetAllocation"] {
  const foodLed = input.vibes.includes("food");
  const cultureLed = input.vibes.includes("culture");

  const flights = 0.3;
  const accommodation = input.nightCount === 0 ? 0.05 : 0.27;
  const food = round2(0.2 + (foodLed ? 0.05 : 0) - (cultureLed ? 0.02 : 0));
  const activities = round2(0.12 + (cultureLed ? 0.05 : 0) - (foodLed ? 0.02 : 0));
  const localTransport = 0.05;
  const buffer = round2(
    1 - flights - accommodation - food - activities - localTransport,
  );

  return { flights, accommodation, food, activities, localTransport, buffer };
}

