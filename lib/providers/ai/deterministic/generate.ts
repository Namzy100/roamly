/**
 * The deterministic planner — the free path, and not a stub.
 *
 * ## Why it implements the same interface
 *
 * It would have been easier to special-case "no provider configured" upstream and
 * hand back a canned itinerary. That would have produced a second code path: the
 * keyless mode — the *default* mode, the one every fresh clone runs — would skip
 * the pool boundary, the mechanical validation, the canonical attachment and the
 * immutable builder that the paid path goes through.
 *
 * So it is a `StructuredGenerator` like the other two. It answers the same
 * requests, its output goes through `validateStrategy` and `validateAssembly`
 * unchanged, and its places come from the same real Overpass search. The only
 * thing it lacks is judgement.
 *
 * ## What it does and does not claim
 *
 * It selects **real OpenStreetMap places**, so the itinerary is geographically
 * honest and every `placeId` is genuine.
 *
 * Its **prose is generic and says so**. A template cannot know that a district is
 * steep, or that a market runs on Tuesdays, and writing "Alfama's medieval streets
 * still run narrow" from a lookup table would be inventing local knowledge — the
 * same offence as inventing a restaurant, in a form that is harder to catch. Every
 * sentence it produces is either mechanically true of the data (a category, a
 * count, a time) or explicitly framed as generic template text. That is why it
 * reads flatter than a model, and why it must.
 *
 * ## Determinism
 *
 * No clock, no randomness, no iteration-order dependence. The same request and the
 * same candidate list produce byte-identical output — which is what makes it
 * usable as the substrate for browser verification, and what makes a failure
 * reproducible.
 */

export function createDeterministicGenerator(): StructuredGenerator {
  return {
    id: "deterministic",
    // A version, not a model name. Nothing downstream can print this and have it
    // read as "generated by a language model".
    model: DETERMINISTIC_MODEL_LABEL,
    generate: (request) => Promise.resolve(generateDeterministically(request)),
  };
}

function generateDeterministically<TSchema extends z.ZodType>(
  request: StructuredGenerationRequest<TSchema>,
): StructuredGenerationResult<unknown> {
  switch (request.operation) {
    case "strategy": {
      const input = StrategyInputSchema.safeParse(request.input);
      if (!input.success) return unavailable("invalid_response");
      return success(buildStrategy(input.data));
    }
    case "assembly": {
      const input = AssemblyInputSchema.safeParse(request.input);
      if (!input.success) return unavailable("invalid_response");
      return success(buildAssembly(input.data));
    }
    case "refinement": {
      /**
       * Refining a trip this planner built.
       *
       * Legitimate rather than a substitution: the orchestrator only routes here
       * when the trip's own provider is `deterministic`. A Gemini trip refined by a
       * template would be swapping planners behind the traveller's back, and
       * `resolveRefinementProvider` refuses that.
       */
      const value = refineDeterministically(request.input);
      if (value === null) return unavailable("invalid_response");
      return success(value);
    }

    case "repair":
      /**
       * Unreachable by construction, and left as a hard failure rather than a
       * silent re-run.
       *
       * This planner's output is validated by the same code as everything else,
       * and it is built to satisfy it. A repair request therefore means the
       * builder below has a bug — and a bug that quietly regenerates the same
       * invalid answer would be invisible. Failing loudly is the point.
       */
      console.error(
        "[roamly] deterministic planner was asked to repair its own output, which means it produced invalid output",
      );
      return unavailable("unknown");
  }
}

function success(value: unknown): StructuredGenerationResult<unknown> {
  return {
    status: "success",
    value,
    provider: "deterministic",
    model: DETERMINISTIC_MODEL_LABEL,
  };
}

