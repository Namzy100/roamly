import { ArrowLeft, CalendarDays, FlaskConical, Users } from "lucide-react";
import Link from "next/link";

import { Badge } from "@/components/ui/badge";
import { formatDateRange, humanizeSlug } from "@/lib/format";
import type { TripPlan } from "@/lib/schemas";

export function TripHeader({ plan }: { plan: TripPlan }) {
  const { request, destination } = plan;

  return (
    <header className="flex flex-col gap-6 border-b border-line bg-cream-raised/60 px-5 pt-6 pb-7 sm:px-8">
      <Link
        href="/"
        className="inline-flex w-fit items-center gap-1.5 rounded-md text-sm text-ink-muted transition-colors hover:text-forest"
      >
        <ArrowLeft aria-hidden className="size-3.5" />
        Plan another trip
      </Link>

      {/**
       * The banner appears **only** for template output — the fixed Lisbon sample
       * and the deterministic demo planner, both of which carry `source: "mock"`.
       *
       * A model-generated trip does not get it, because it would be false: those
       * stops really were chosen for this request. What that trip gets instead is
       * `GenerationProvenance` further down, naming the planner and the data source.
       * Showing this banner on a generated plan would be as misleading as omitting it
       * from the sample.
       */}
      {plan.source === "mock" ? <SampleBanner /> : null}

      <div className="flex flex-col gap-4">
        <div className="flex flex-col gap-2">
          <span className="eyebrow text-terracotta">
            {destination.city}, {destination.country}
          </span>
          <h1 className="font-display text-3xl leading-tight tracking-tight text-forest text-balance sm:text-4xl lg:text-5xl">
            {request.departureCity} to {destination.city}
          </h1>
        </div>

        <div className="flex flex-wrap items-center gap-x-4 gap-y-2 text-sm text-ink-muted">
          <span className="inline-flex items-center gap-1.5">
            <CalendarDays aria-hidden className="size-3.5" />
            {formatDateRange(request.startDate, request.endDate)}
            <span aria-hidden>·</span>
            {plan.days.length} days
          </span>
          <span className="inline-flex items-center gap-1.5">
            <Users aria-hidden className="size-3.5" />
            {request.travelers}{" "}
            {request.travelers === 1 ? "traveller" : "travellers"}
          </span>
        </div>

        <div className="flex flex-wrap gap-1.5">
          <Badge className="rounded-full bg-forest px-2.5 text-[0.6875rem] font-medium">
            {humanizeSlug(request.pace)} pace
          </Badge>
          {request.vibes.map((vibe) => (
            <Badge
              key={vibe}
              variant="secondary"
              className="rounded-full px-2.5 text-[0.6875rem] font-medium"
            >
              {humanizeSlug(vibe)}
            </Badge>
          ))}
          {request.dietary
            .filter((preference) => preference !== "none")
            .map((preference) => (
              <Badge
                key={preference}
                variant="outline"
                className="rounded-full px-2.5 text-[0.6875rem] font-medium"
              >
                {humanizeSlug(preference)}
              </Badge>
            ))}
        </div>
      </div>

      <div className="grid gap-5 lg:grid-cols-[1.6fr_1fr]">
        <p className="text-[0.9375rem] leading-relaxed text-ink-muted text-pretty">
          {destination.overview}
        </p>

        <div className="flex flex-col gap-1.5 rounded-2xl border border-line bg-cream-raised p-4">
          <span className="eyebrow text-ink-muted">Recommended base</span>
          <p className="font-display text-xl text-forest">
            {destination.recommendedNeighborhood.name}
          </p>
          <p className="text-xs leading-relaxed text-ink-muted text-pretty">
            {destination.recommendedNeighborhood.why}
          </p>
        </div>
      </div>
    </header>
  );
}

/**
 * Template output, labelled.
 *
 * The wording covers both cases it can appear for without claiming either: the fixed
 * sample returns the same Lisbon plan every time, and the demo planner selects real
 * places but writes generic commentary. Both are "not generated by a model", which is
 * the thing a visitor needs to know.
 */
function SampleBanner() {
  return (
    <p
      data-testid="sample-banner"
      className="flex items-start gap-2 rounded-xl border border-terracotta/30 bg-terracotta/[0.07] px-3.5 py-2.5 text-xs leading-relaxed text-ink"
    >
      <FlaskConical
        aria-hidden
        className="mt-0.5 size-3.5 shrink-0 text-terracotta"
      />
      <span>
        <span className="font-semibold">Built by the Demo Planner.</span> This plan
        came from a deterministic template rather than a language model, so its
        commentary is generic — though its places are real. Prices throughout are
        planning estimates, never live figures. Your own answers are shown below.
      </span>
    </p>
  );
}
